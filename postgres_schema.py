from postgres_db import get_postgres_connection

def initialize_postgres():
    """Initialize tables with a dedicated operator/admin connection."""
    with get_postgres_connection(admin=True) as db:
        with db.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS api_keys (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    customer_name TEXT NOT NULL, key_hash TEXT NOT NULL UNIQUE,
                    created_at TIMESTAMPTZ NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE
                )
            """)
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS usage_monthly (
                    customer_id BIGINT NOT NULL REFERENCES api_keys(id),
                    month TEXT NOT NULL, requests INTEGER NOT NULL DEFAULT 0 CHECK (requests >= 0),
                    PRIMARY KEY (customer_id, month)
                )
            """)
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS customer_plans (
                    customer_id BIGINT PRIMARY KEY REFERENCES api_keys(id),
                    monthly_limit INTEGER NOT NULL DEFAULT 100 CHECK (monthly_limit >= 0)
                )
            """)
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS request_rate_limits (
                    customer_id BIGINT PRIMARY KEY, window_start TIMESTAMPTZ NOT NULL,
                    request_count INTEGER NOT NULL CHECK (request_count >= 0)
                )
            """)
    return True
